from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from memory_ingest.config import Settings, get_settings
from memory_ingest.seed.docs import (
    load_chapter,
    render_emotion_catalog,
    render_prompt,
)
from memory_ingest.seed.emotions import EmotionMatcher, ModelChooser, build_matcher
from memory_ingest.seed.model import SeedModel, SeedModelUnavailable
from memory_ingest.seed.normalize import normalize_emotions_in_file
from memory_ingest.seed.parse import SeedRecord, parse_and_validate
from memory_ingest.seed.writer import (
    MemoryWriter,
    SeedLedger,
    SeedWriteError,
    plan_and_write,
)

APPROVAL_RE = re.compile(r"^\s*status\s*:\s*approved\s*$", re.IGNORECASE | re.MULTILINE)


def _settings() -> Settings:
    return get_settings()


def _chapter_slug(label: str) -> str:
    m = re.search(r"(\d+)", label)
    return m.group(1).zfill(2) if m else label.strip().lower().replace(" ", "-")


def _report(records: list[SeedRecord]) -> int:
    ok = [r for r in records if r.ok]
    bad = [r for r in records if not r.ok]
    for r in records:
        mark = "  " if r.ok else "!!"
        extras = []
        if r.anchor:
            extras.append("ANCHOR")
        if r.beat:
            extras.append(f"beat:{r.beat}")
        if r.category:
            extras.append(f"category:{r.category}")
        if r.revises:
            extras.append(f"revises:{r.revises[:13]}")
        print(f"{mark} {r.n:>3}. {r.title[:44]:44} {r.type:10} {r.subject_class:9}"
              f" {(r.emotion_resolved or r.emotion_name)[:14]:14} {' '.join(extras)}")
        for p in r.problems:
            print(f"       ↳ {p}")
    print(f"\n{len(ok)} valid · {len(bad)} flagged (flagged records are never written)")
    return len(bad)


def _generate_one(
    s: Settings, template_path: str, label: str, chapter_text: str, extra: dict[str, str]
) -> str:
    template = Path(template_path).expanduser().read_text(encoding="utf-8")
    prompt = render_prompt(template, label=label, chapter_text=chapter_text, **extra)
    model = SeedModel(s)
    print(f"  generating with {model.name} @ {s.seed_model_base} "
          f"(temp {model.temperature}, budget {model.max_tokens})…", file=sys.stderr)
    try:
        return model.complete(prompt)
    finally:
        model.close()


def _draft_header(label: str, model_name: str, pass_name: str) -> str:
    'Files land UNAPPROVED: a human writes the approval line, never a model.'
    return (f"status: draft\n<!-- {label} · {pass_name} · generated by {model_name}\n"
            f"     Review, edit, then change the line above to "
            f"`status: approved` before ingesting. -->\n\n")


def cmd_generate(args: argparse.Namespace) -> int:
    s = _settings()
    prompt_path = args.prompt or s.seed_prompt_path
    if not prompt_path:
        print("no prompt: set SEED_PROMPT_PATH or pass --prompt", file=sys.stderr)
        return 2
    chapter_text = load_chapter(args.chapter)
    slug = _chapter_slug(args.label)
    outdir = Path(args.out).parent if args.out else Path(s.seed_outdir).expanduser()
    outdir.mkdir(parents=True, exist_ok=True)

    try:
        catalog = _catalog(s)
        emotions = {"EMOTION_CATALOG": render_emotion_catalog(catalog)}
        print(f"  ({len(catalog)} catalog emotions in both prompts)", file=sys.stderr)
    except Exception as exc:  # noqa: BLE001 - a prompt without it still works
        print(f"  (catalog unavailable, prompts unfilled: {exc})", file=sys.stderr)
        emotions = {"EMOTION_CATALOG": ""}

    try:
        print("pass 1/2 — episodes", file=sys.stderr)
        episodes = _generate_one(s, prompt_path, args.label, chapter_text, emotions)
        ep_out = Path(args.out) if args.out else outdir / f"Chapter_{slug}_Memories.md"
        ep_out.write_text(
            _draft_header(args.label, s.seed_model_name, "Pass 1 · episodes")
            + episodes.strip() + "\n", encoding="utf-8")
        written = [ep_out]

        facts_prompt = args.facts_prompt or s.seed_facts_prompt_path
        if not args.single_pass and facts_prompt:
            print("pass 2/2 — facts + preferences (sees pass 1)", file=sys.stderr)
            facts = _generate_one(
                s, facts_prompt, args.label, chapter_text,
                {"EPISODES": episodes, **emotions}
            )
            f_out = outdir / f"Chapter_{slug}_Facts.md"
            f_out.write_text(
                _draft_header(args.label, s.seed_model_name, "Pass 2 · facts")
                + facts.strip() + "\n", encoding="utf-8")
            written.append(f_out)
        elif not args.single_pass:
            print("  (no SEED_FACTS_PROMPT_PATH — pass 1 only)", file=sys.stderr)
    except SeedModelUnavailable as exc:
        print(f"model unavailable: {exc}", file=sys.stderr)
        return 1

    print()
    _normalize(written, s)

    print()
    for path in written:
        n = len(parse_and_validate(path.read_text(encoding="utf-8"), catalog=[]))
        print(f"wrote {path}  ({n} records)")
    print("\nreview them, then:")
    for path in written:
        print(f"  seed ingest {path} --approved")
    return 0


def _matcher(s: Settings, catalog: list[dict]) -> "EmotionMatcher | None":
    "The emotion matcher, or None when it can't be built."
    if not s.embed_key:
        print("  (no EMBED_KEY — emotion normalisation skipped)", file=sys.stderr)
        return None
    chooser: ModelChooser | None = None
    if s.seed_model_key:
        chooser = ModelChooser(SeedModel(s))
    else:
        print("  (no SEED_MODEL_KEY — emotions gated but not chosen)",
              file=sys.stderr)
    return build_matcher(catalog, base_url=s.embed_base, api_key=s.embed_key,
                         chooser=chooser,
                         cache_path=Path(s.emotion_cache).expanduser(),
                         floor=s.emotion_floor)


def _normalize(paths: list[Path], s: Settings) -> None:
    'The review step: snap every stray emotion, in place, visibly.'
    try:
        matcher = _matcher(s, _catalog(s))
    except Exception as exc:  # noqa: BLE001 - never lose a generation to this
        print(f"  (emotion normalisation unavailable: {exc})", file=sys.stderr)
        return
    if matcher is None:
        return
    for path in paths:
        result = normalize_emotions_in_file(path, matcher)
        if not result:
            print(f"emotions in {path.name}: all valid")
            continue
        if result.substitutions:
            print(f"emotions corrected in {path.name}:")
            for sub in result.substitutions:
                print(f"  {sub.line()[2:]}")
        if result.unresolved:
            print(f"STILL FLAGGED in {path.name} — not emotions, fix by hand: "
                  + ", ".join(result.unresolved))


def _catalog(s: Settings) -> list[dict]:
    'The 127-emotion catalog, read with the seed key (read-only call).'
    w = MemoryWriter(s.harness_base, s.seed_key or s.harness_key)
    try:
        return w.emotions()
    finally:
        w.close()


def cmd_parse(args: argparse.Namespace) -> int:
    s = _settings()
    text = Path(args.md).expanduser().read_text(encoding="utf-8")
    records = parse_and_validate(text, catalog=_catalog(s))
    return 1 if _report(records) else 0


def cmd_ingest(args: argparse.Namespace) -> int:
    s = _settings()
    path = Path(args.md).expanduser()
    text = path.read_text(encoding="utf-8")

    approved_in_file = bool(APPROVAL_RE.search(text))
    if not (args.approved and approved_in_file):
        print("REFUSED — seeded memories become her identity and her training data.",
              file=sys.stderr)
        if not approved_in_file:
            print(f"  {path.name} has no `status: approved` line "
                  "(a human must review and mark it)", file=sys.stderr)
        if not args.approved:
            print("  --approved was not passed", file=sys.stderr)
        return 2

    records = parse_and_validate(text, catalog=_catalog(s))
    flagged = _report(records)
    if flagged and not args.force:
        print("\nflagged records above will be SKIPPED; re-run with --force to "
              "proceed anyway (they are still never written)", file=sys.stderr)

    chapter = args.chapter or _chapter_slug(path.stem)
    ledger = SeedLedger(s.seed_ledger)
    writer = None
    try:
        if not args.dry_run:
            writer = MemoryWriter(s.harness_base, s.seed_key)
            who = writer.whoami()
            if who.get("trust_ceiling") != "user":
                print(f"REFUSED — seed key authors as {who.get('principal_id')!r}, "
                      "and requires user trust", file=sys.stderr)
                return 2
            print(f"\nwriting as {who['principal_id']} "
                  f"(trust {who['trust_ceiling']}) → {s.harness_base}")
        outcomes = plan_and_write(records, chapter=chapter, writer=writer,
                                  ledger=ledger, dry_run=args.dry_run)
    except SeedWriteError as exc:
        print(f"write failed: {exc}", file=sys.stderr)
        return 1
    finally:
        if writer:
            writer.close()
        ledger.close()

    verb = "would " if args.dry_run else ""
    for o in outcomes:
        print(f"  {verb}{o.action:6} {o.n:>3}. {o.title[:44]:44} "
              f"{o.lineage_id[:13]} rev{o.revision}")
    counts = {a: sum(1 for o in outcomes if o.action == a) for a in ("mint", "revise", "skip")}
    print(f"\n{counts['mint']} minted · {counts['revise']} revised · {counts['skip']} unchanged"
          + (" (dry run — nothing written)" if args.dry_run else ""))
    return 0


def cmd_link(args: argparse.Namespace) -> int:
    'Join everything that came from the same scene beat.'
    s = _settings()
    ledger = SeedLedger(s.seed_ledger)
    writer = MemoryWriter(s.harness_base, s.seed_key)
    try:
        beats = ledger.beats(args.chapter)
        if not beats:
            print(f"no beats recorded for chapter {args.chapter} — ingest first")
            return 1
        made = skipped = 0
        for beat, members in sorted(beats.items()):
            episodes = [m for m in members if m["track"] == "ep"]
            others = [m for m in members if m["track"] != "ep"]
            if len(members) < 2:
                continue
            targets = episodes[:1] or others[:1]
            for m in members:
                for t in targets:
                    if m["lineage_id"] == t["lineage_id"]:
                        continue
                    if args.dry_run:
                        if (t["lineage_id"], "relates_to") in writer.links_from(
                            m["lineage_id"]
                        ):
                            skipped += 1
                        else:
                            made += 1
                        continue
                    r = writer.link_once(m["lineage_id"], t["lineage_id"], "relates_to")
                    made += 1 if r else 0
                    skipped += 0 if r else 1
            print(f"  beat:{beat:24} {len(members)} members")
        verb = "would create" if args.dry_run else "created"
        print(f"\n{verb} {made} relates_to link(s); {skipped} already present")
        return 0
    except SeedWriteError as exc:
        print(f"link failed: {exc}", file=sys.stderr)
        return 1
    finally:
        writer.close()
        ledger.close()


def cmd_normalize(args: argparse.Namespace) -> int:
    s = _settings()
    _normalize([Path(m).expanduser() for m in args.md], s)
    return 0


def cmd_run(args: argparse.Namespace) -> int:
    rc = cmd_generate(args)
    if rc == 0:
        print("\nSTOP: review the file above before ingesting. Nothing has been "
              "written to her memory.")
    return rc


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="seed", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    for name, fn in (("generate", cmd_generate), ("run", cmd_run)):
        p = sub.add_parser(name, help="chapter → reviewable memories markdown")
        p.add_argument("chapter", help=".docx / .txt / .md chapter file")
        p.add_argument("--label", required=True, help='e.g. "Chapter 02"')
        p.add_argument("--out", default=None)
        p.add_argument("--prompt", default=None, help="override SEED_PROMPT_PATH")
        p.add_argument("--facts-prompt", default=None,
                       help="override SEED_FACTS_PROMPT_PATH (pass 2)")
        p.add_argument("--single-pass", action="store_true",
                       help="episodes only; skip the facts pass")
        p.set_defaults(func=fn)

    p = sub.add_parser("link", help="join same-beat memories with relates_to")
    p.add_argument("chapter", help="chapter key used at ingest, e.g. 02")
    p.add_argument("--dry-run", action="store_true")
    p.set_defaults(func=cmd_link)

    p = sub.add_parser("normalize",
                       help="snap stray emotions in a .md to the 127-catalog")
    p.add_argument("md", nargs="+")
    p.set_defaults(func=cmd_normalize)

    p = sub.add_parser("parse", help="inspect a memories file — no writes")
    p.add_argument("md")
    p.set_defaults(func=cmd_parse)

    p = sub.add_parser("ingest", help="write an APPROVED memories file to her memory")
    p.add_argument("md")
    p.add_argument("--approved", action="store_true",
                   help="required, together with a `status: approved` line in the file")
    p.add_argument("--dry-run", action="store_true", help="plan only, write nothing")
    p.add_argument("--chapter", default=None, help="ledger chapter key (default: from filename)")
    p.add_argument("--force", action="store_true", help="proceed despite flagged records")
    p.set_defaults(func=cmd_ingest)
    return ap


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
